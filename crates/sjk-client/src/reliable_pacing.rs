//! Client-side pacing for reliable (string) commands.
//!
//! Stock servers silently discard any client command that arrives within
//! `sv_floodProtect` (1000 ms) of the previously accepted one once the client
//! is active: `SV_ClientCommand` (`codemp/server/sv_client.cpp:1274-1296`)
//! advances `lastClientCommand` but executes the string with `clientOk ==
//! qfalse`. Nothing tells the client. A stock player rarely types two commands
//! in a second; a shell that emits `userinfo`, `forcechanged` and `team` in
//! one burst loses everything after the first (EFF JA+ server,
//! `target/parity-reports/playtest-japlus5`). Commands still leave through the
//! ordinary reliable path — only their release time is spaced out.
//!
//! What the player sends is paced too, but differently
//! ([`ReliableCommandOrigin`]): a bind or console command pressed again while
//! the same one still waits is not queued twice, and one that waited longer
//! than [`INPUT_COMMAND_TTL`] is dropped instead of sent late, as a stock
//! client's flood extras are dropped by the server. Pressing `amhug` twenty
//! times used to queue twenty hugs released one a second, long after the
//! player stopped (hub report 73, 17/10/2026). Typed chat is deduplicated but
//! never expires: a message the player wrote is still worth reading late,
//! while a late action fires in a situation the player has left.
//!
//! What the player sends also goes ahead of the client's own `score` requests still
//! waiting (one every two seconds while dead or holding the scoreboard), so typed chat
//! leaves in the next window instead of queueing behind them a second each (hub report
//! 172). It stays behind the client's other commands (a `userinfo` after a model or
//! saber change, a Force-profile `team` retry): a `kill` bind must not respawn the
//! player before the new model is sent, nor a typed `/team s` be undone by a retry
//! sent after it. Both keep their order among themselves.
//!
//! Commands sent while the server still considers the client `CS_PRIMED`
//! (the connect and map-restart bootstrap packets) are exempt and are not
//! routed through here.

use std::collections::VecDeque;
use std::time::{Duration, Instant};

/// `sv_floodProtect` default window plus transport jitter margin.
pub const DEFAULT_COMMAND_INTERVAL: Duration = Duration::from_millis(1_050);
/// How long a player's bind or console command may wait for its window.
///
/// Longer than one interval, so a command pressed just after another still
/// goes out in the next window; shorter than two, so it never fires seconds
/// after the press.
pub const INPUT_COMMAND_TTL: Duration = Duration::from_millis(1_500);
/// Outbox bound; more than this means a runaway caller, not a slow server.
const MAX_QUEUED: usize = 64;

/// Who asked for a reliable command, which decides how it waits.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum ReliableCommandOrigin {
    /// Generated by the client (userinfo, Force-profile replies, team
    /// retries, menus): always kept, in order, until released.
    #[default]
    System,
    /// A player's bind or console command: not queued twice while an
    /// identical one waits, dropped after [`INPUT_COMMAND_TTL`].
    Input,
    /// Chat the player typed: not queued twice while identical chat waits,
    /// never dropped.
    Chat,
    /// One part of a divided chat message: every occurrence is kept, including
    /// identical adjacent parts, and it never expires.
    ChatPart,
}

#[derive(Debug)]
struct Queued {
    command: Vec<u8>,
    origin: ReliableCommandOrigin,
    /// Latest release time for [`ReliableCommandOrigin::Input`].
    expires: Option<Instant>,
}

impl Queued {
    /// The client's own scoreboard request, which a player's command may pass.
    fn is_score_request(&self) -> bool {
        self.origin == ReliableCommandOrigin::System && self.command == b"score"
    }
}

/// Unsequenced outbox that releases one command per interval.
#[derive(Debug)]
pub(crate) struct ReliableCommandPacer {
    interval: Duration,
    last_sent: Option<Instant>,
    outbox: VecDeque<Queued>,
}

impl ReliableCommandPacer {
    pub(crate) fn new(interval: Duration) -> Self {
        Self {
            interval,
            last_sent: None,
            outbox: VecDeque::new(),
        }
    }

    /// Queue a command; `false` when the outbox is full.
    ///
    /// An input or chat command identical to one of the same origin still
    /// waiting is folded into it (an input one's deadline restarts from `now`,
    /// its place is kept) and counts as accepted. A new one goes ahead of the
    /// `score` requests waiting at the end of the outbox, and nothing else.
    pub(crate) fn push(
        &mut self,
        command: Vec<u8>,
        origin: ReliableCommandOrigin,
        now: Instant,
    ) -> bool {
        self.drop_expired(now);
        let expires = (origin == ReliableCommandOrigin::Input).then(|| now + INPUT_COMMAND_TTL);
        if matches!(
            origin,
            ReliableCommandOrigin::Input | ReliableCommandOrigin::Chat
        ) && let Some(waiting) = self
            .outbox
            .iter_mut()
            .find(|queued| queued.origin == origin && queued.command == command)
        {
            waiting.expires = expires;
            return true;
        }
        if self.outbox.len() >= MAX_QUEUED {
            return false;
        }
        let queued = Queued {
            command,
            origin,
            expires,
        };
        if origin == ReliableCommandOrigin::System {
            self.outbox.push_back(queued);
        } else {
            let after = self
                .outbox
                .iter()
                .rposition(|queued| !queued.is_score_request())
                .map_or(0, |index| index + 1);
            self.outbox.insert(after, queued);
        }
        true
    }

    /// The next command whose release time has come, marking it sent.
    pub(crate) fn pop_due(&mut self, now: Instant) -> Option<Vec<u8>> {
        self.drop_expired(now);
        if self.outbox.is_empty() {
            return None;
        }
        if let Some(last) = self.last_sent
            && now.saturating_duration_since(last) < self.interval
        {
            return None;
        }
        self.last_sent = Some(now);
        self.outbox.pop_front().map(|queued| queued.command)
    }

    /// Commands still waiting for their release time.
    pub(crate) fn queued(&self) -> usize {
        self.outbox.len()
    }

    /// Forget everything queued, e.g. across a gamestate replacement.
    pub(crate) fn clear(&mut self) {
        self.outbox.clear();
        self.last_sent = None;
    }

    /// Drop input commands that waited past their deadline.
    fn drop_expired(&mut self, now: Instant) {
        self.outbox
            .retain(|queued| queued.expires.is_none_or(|expires| now <= expires));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ms(millis: u64) -> Duration {
        Duration::from_millis(millis)
    }

    fn pacer() -> ReliableCommandPacer {
        ReliableCommandPacer::new(DEFAULT_COMMAND_INTERVAL)
    }

    #[test]
    fn system_commands_are_all_kept_in_order() {
        let start = Instant::now();
        let mut pacer = pacer();
        let commands: [&[u8]; 4] = [b"userinfo", b"forcechanged", b"team s", b"team s"];
        for command in commands {
            assert!(pacer.push(command.to_vec(), ReliableCommandOrigin::System, start));
        }
        assert_eq!(pacer.queued(), 4);
        let mut sent = Vec::new();
        for step in 0..4 {
            let now = start + ms(step * 1_100 + 5_000);
            sent.push(pacer.pop_due(now).expect("due"));
        }
        assert_eq!(sent, commands);
    }

    #[test]
    fn repeated_input_command_waits_once() {
        let start = Instant::now();
        let mut pacer = pacer();
        assert!(pacer.push(b"amhug".to_vec(), ReliableCommandOrigin::Input, start));
        assert_eq!(pacer.pop_due(start).as_deref(), Some(&b"amhug"[..]));
        for press in 1..20 {
            let now = start + ms(press * 50);
            assert!(pacer.push(b"amhug".to_vec(), ReliableCommandOrigin::Input, now));
            assert_eq!(pacer.pop_due(now), None);
        }
        assert_eq!(pacer.queued(), 1);
        let window = start + DEFAULT_COMMAND_INTERVAL;
        assert_eq!(pacer.pop_due(window).as_deref(), Some(&b"amhug"[..]));
        assert_eq!(pacer.queued(), 0);
        assert_eq!(pacer.pop_due(window + ms(10_000)), None);
    }

    #[test]
    fn input_command_expires_instead_of_firing_late() {
        let start = Instant::now();
        let mut pacer = pacer();
        let chat: [&[u8]; 3] = [b"say a", b"say b", b"say c"];
        for command in chat {
            pacer.push(command.to_vec(), ReliableCommandOrigin::Chat, start);
        }
        pacer.push(b"amhug".to_vec(), ReliableCommandOrigin::Input, start);
        let mut sent = Vec::new();
        for step in 0..6 {
            if let Some(command) = pacer.pop_due(start + ms(step * 1_050)) {
                sent.push(command);
            }
        }
        assert_eq!(sent, chat);
        assert_eq!(pacer.queued(), 0);
    }

    #[test]
    fn input_command_inside_its_lifetime_still_goes_out() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"amhug".to_vec(), ReliableCommandOrigin::Input, start);
        assert!(pacer.pop_due(start).is_some());
        pacer.push(
            b"amkiss".to_vec(),
            ReliableCommandOrigin::Input,
            start + ms(100),
        );
        assert_eq!(
            pacer.pop_due(start + DEFAULT_COMMAND_INTERVAL).as_deref(),
            Some(&b"amkiss"[..])
        );
    }

    #[test]
    fn pressing_again_restarts_the_lifetime() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"say a".to_vec(), ReliableCommandOrigin::Chat, start);
        pacer.push(b"say b".to_vec(), ReliableCommandOrigin::Chat, start);
        assert!(pacer.pop_due(start).is_some());
        pacer.push(b"amhug".to_vec(), ReliableCommandOrigin::Input, start);
        pacer.push(
            b"amhug".to_vec(),
            ReliableCommandOrigin::Input,
            start + ms(1_000),
        );
        assert_eq!(pacer.queued(), 2);
        assert!(pacer.pop_due(start + ms(1_050)).is_some());
        assert_eq!(
            pacer.pop_due(start + ms(2_100)).as_deref(),
            Some(&b"amhug"[..])
        );
    }

    #[test]
    fn chat_is_deduplicated_but_never_expires() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"say hi".to_vec(), ReliableCommandOrigin::Chat, start);
        for _ in 0..3 {
            pacer.push(b"say gg".to_vec(), ReliableCommandOrigin::Chat, start);
        }
        pacer.push(b"say wp".to_vec(), ReliableCommandOrigin::Chat, start);
        assert_eq!(pacer.queued(), 3);
        assert!(pacer.pop_due(start).is_some());
        let late = start + ms(30_000);
        assert_eq!(pacer.pop_due(late).as_deref(), Some(&b"say gg"[..]));
        assert_eq!(
            pacer.pop_due(late + DEFAULT_COMMAND_INTERVAL).as_deref(),
            Some(&b"say wp"[..])
        );
    }

    #[test]
    fn identical_parts_of_one_chat_message_are_all_kept() {
        let start = Instant::now();
        let mut pacer = pacer();
        for _ in 0..3 {
            assert!(pacer.push(
                b"say repeated".to_vec(),
                ReliableCommandOrigin::ChatPart,
                start,
            ));
        }
        assert_eq!(pacer.queued(), 3);
        for step in 0..3 {
            assert_eq!(
                pacer
                    .pop_due(start + DEFAULT_COMMAND_INTERVAL * step)
                    .as_deref(),
                Some(&b"say repeated"[..])
            );
        }
    }

    #[test]
    fn player_commands_go_ahead_of_waiting_score_requests_only() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        assert!(pacer.pop_due(start).is_some());
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"say gg".to_vec(), ReliableCommandOrigin::Chat, start);
        // Pressed late enough to still be alive in the second window.
        pacer.push(
            b"amhug".to_vec(),
            ReliableCommandOrigin::Input,
            start + ms(1_000),
        );
        let mut sent = Vec::new();
        for step in 1..=4 {
            sent.extend(pacer.pop_due(start + ms(step * 1_050)));
        }
        let expected: [&[u8]; 4] = [b"say gg", b"amhug", b"score", b"score"];
        assert_eq!(sent, expected);
    }

    #[test]
    fn player_commands_stay_behind_the_clients_other_commands() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        assert!(pacer.pop_due(start).is_some());
        // A model changed in a menu, then a `kill` bind: the new model goes first,
        // so the player respawns with it. A typed `/team s` lands after a waiting
        // Force-profile retry, so the retry cannot undo it.
        pacer.push(b"userinfo".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"team r".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        // Pressed late enough to still be alive when their windows come.
        pacer.push(
            b"kill".to_vec(),
            ReliableCommandOrigin::Input,
            start + ms(2_000),
        );
        pacer.push(
            b"team s".to_vec(),
            ReliableCommandOrigin::Input,
            start + ms(3_000),
        );
        let mut sent = Vec::new();
        for step in 1..=5 {
            sent.extend(pacer.pop_due(start + ms(step * 1_050)));
        }
        let expected: [&[u8]; 5] = [b"userinfo", b"team r", b"kill", b"team s", b"score"];
        assert_eq!(sent, expected);
    }

    #[test]
    fn origins_do_not_fold_into_each_other() {
        let start = Instant::now();
        let mut pacer = pacer();
        pacer.push(b"userinfo".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::System, start);
        pacer.push(b"score".to_vec(), ReliableCommandOrigin::Input, start);
        assert_eq!(pacer.queued(), 3);
    }

    #[test]
    fn full_outbox_still_folds_duplicates() {
        let start = Instant::now();
        let mut pacer = pacer();
        assert!(pacer.push(b"say gg".to_vec(), ReliableCommandOrigin::Chat, start));
        for index in 1..MAX_QUEUED {
            let command = format!("cmd {index}").into_bytes();
            assert!(pacer.push(command, ReliableCommandOrigin::System, start));
        }
        assert!(!pacer.push(b"other".to_vec(), ReliableCommandOrigin::System, start));
        assert!(pacer.push(b"say gg".to_vec(), ReliableCommandOrigin::Chat, start));
    }
}
